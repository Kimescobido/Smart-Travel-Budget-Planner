<?php
require_once __DIR__ . '/../config/db.php';
require_once __DIR__ . '/../includes/auth_check.php';
requireLogin();

$trip_id = $_POST['trip_id'] ?? null;
if (!$trip_id) {
    header("Location: ../trips.php");
    exit;
}

// Fetch trip details
$stmt = $pdo->prepare("SELECT * FROM trips WHERE id = :id AND (user_id = :uid OR :is_admin = 'admin')");
$stmt->execute([
    'id' => $trip_id,
    'uid' => $_SESSION['user_id'],
    'is_admin' => $_SESSION['user_role'] ?? 'user'
]);
$trip = $stmt->fetch();

if (!$trip) {
    die("Trip not found or unauthorized.");
}

// Fetch user email
$userStmt = $pdo->prepare("SELECT email, name FROM users WHERE id = :uid");
$userStmt->execute(['uid' => $trip['user_id']]);
$user = $userStmt->fetch();

$recipientEmail = $user['email'] ?? $_SESSION['user_email'];
$recipientName = $user['name'] ?? $_SESSION['user_name'];

// Fetch all itinerary items
$itemsStmt = $pdo->prepare("SELECT * FROM itinerary_items WHERE trip_id = :tid ORDER BY day_number ASC, id ASC");
$itemsStmt->execute(['tid' => $trip['id']]);
$items = $itemsStmt->fetchAll();

// Build email HTML body
$itemsHtml = '';
if (empty($items)) {
    $itemsHtml = '<tr><td colspan="4" style="text-align:center; padding:12px; color:#888;">No activities logged yet.</td></tr>';
} else {
    foreach ($items as $item) {
        $itemsHtml .= '
        <tr>
            <td style="padding:10px; border-bottom:1px solid #eee;"><strong>Day ' . htmlspecialchars($item['day_number']) . '</strong></td>
            <td style="padding:10px; border-bottom:1px solid #eee;">' . htmlspecialchars($item['activity_title']) . '</td>
            <td style="padding:10px; border-bottom:1px solid #eee;">' . htmlspecialchars($item['local_currency']) . ' ' . number_format($item['cost_local'], 2) . '</td>
            <td style="padding:10px; border-bottom:1px solid #eee; color:#666; font-size:12px;">' . htmlspecialchars($item['notes'] ?? '-') . '</td>
        </tr>';
    }
}

$emailContent = '
<!DOCTYPE html>
<html>
<body style="font-family: Arial, sans-serif; line-height: 1.6; color: #333; background-color: #f4f6f9; padding: 20px;">
    <div style="max-width: 600px; margin: auto; background: #ffffff; border-radius: 8px; overflow: hidden; border: 1px solid #e0e0e0;">
        <div style="background-color: #0d6efd; color: white; padding: 20px; text-align: center;">
            <h1 style="margin: 0; font-size: 24px;">✈️ ' . htmlspecialchars($trip['title']) . '</h1>
            <p style="margin: 5px 0 0; font-size: 14px; opacity: 0.9;">Destination: ' . htmlspecialchars($trip['destination_city']) . '</p>
        </div>
        <div style="padding: 20px;">
            <p>Hello <strong>' . htmlspecialchars($recipientName) . '</strong>,</p>
            <p>Here is your full travel itinerary and budget breakdown generated from <strong>Smart Travel Planner</strong>:</p>
            
            <div style="background: #f8f9fa; padding: 15px; border-radius: 6px; margin-bottom: 20px;">
                <p style="margin: 0 0 5px;"><strong>📅 Travel Dates:</strong> ' . date('M d, Y', strtotime($trip['start_date'])) . ' to ' . date('M d, Y', strtotime($trip['end_date'])) . '</p>
                <p style="margin: 0;"><strong>💰 Total Budget:</strong> ' . htmlspecialchars($trip['base_currency']) . ' ' . number_format($trip['total_budget'], 2) . '</p>
            </div>

            <h3 style="border-bottom: 2px solid #0d6efd; padding-bottom: 5px;">Daily Schedule & Expenses</h3>
            <table style="width: 100%; border-collapse: collapse; text-align: left; font-size: 14px;">
                <thead>
                    <tr style="background: #f1f1f1;">
                        <th style="padding: 10px;">Day</th>
                        <th style="padding: 10px;">Activity</th>
                        <th style="padding: 10px;">Cost</th>
                        <th style="padding: 10px;">Notes</th>
                    </tr>
                </thead>
                <tbody>
                    ' . $itemsHtml . '
                </tbody>
            </table>

            <p style="margin-top: 30px; font-size: 12px; color: #888; text-align: center;">
                Generated by Smart Travel Planner • API Integrated System
            </p>
        </div>
    </div>
</body>
</html>';

$apiKey = getenv('RESEND_API_KEY');

if (empty($apiKey)) {
    header("Location: ../trip_view.php?id=" . $trip['id'] . "&email_status=no_key");
    exit;
}

// Call Resend REST API via cURL
$postData = [
    'from' => 'Smart Travel Planner <onboarding@resend.dev>',
    'to' => [$recipientEmail],
    'subject' => 'Your Itinerary: ' . $trip['title'],
    'html' => $emailContent
];

$ch = curl_init('https://api.resend.com/emails');
curl_setopt($ch, CURLOPT_HTTPHEADER, [
    'Authorization: Bearer ' . $apiKey,
    'Content-Type: application/json'
]);
curl_setopt($ch, CURLOPT_POST, true);
curl_setopt($ch, CURLOPT_POSTFIELDS, json_encode($postData));
curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
curl_setopt($ch, CURLOPT_SSL_VERIFYPEER, false);
$response = curl_exec($ch);
$httpCode = curl_getinfo($ch, CURLINFO_HTTP_CODE);
curl_close($ch);

if ($httpCode >= 200 && $httpCode < 300) {
    header("Location: ../trip_view.php?id=" . $trip['id'] . "&email_status=success");
} else {
    // If recipient email isn't verified in testing, Resend returns an error
    header("Location: ../trip_view.php?id=" . $trip['id'] . "&email_status=error");
}
exit;